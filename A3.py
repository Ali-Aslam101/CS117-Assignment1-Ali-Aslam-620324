colour = input("Enter band colour: ")

if colour == "black" or colour == "Black":
    print("Digit = 0")
elif colour == "brown" or colour == "Brown":
    print("Digit = 1")
elif colour == "red" or colour == "Red":
    print("Digit = 2")
elif colour == "orange" or colour == "Orange":
    print("Digit = 3")
elif colour == "yellow" or colour == "Yellow":
    print("Digit = 4")
elif colour == "green" or colour == "Green":
    print("Digit = 5")
elif colour == "blue" or colour == "Blue":
    print("Digit = 6")
elif colour == "violet" or colour == "Violet":
    print("Digit = 7")
elif colour == "grey" or colour == "Grey" or colour == "gray" or colour == "Gray":
    print("Digit = 8")
elif colour == "white" or colour == "White":
    print("Digit = 9")
else:
    print("Invalid colour")
